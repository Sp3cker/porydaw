/// Returns whether the macro carries a sample, wave, or sub-voicegroup symbol.
public func vgMacroHasSymbol(_ macro: VgMacro) -> Bool {
    switch macro {
    case .directSound, .directSoundNoResample, .directSoundAlt,
         .progWave, .progWaveAlt, .keysplit, .keysplitAll: true
    case .square1, .square1Alt, .square2, .square2Alt, .noise, .noiseAlt: false
    }
}

/// Returns whether the macro uses the narrower CGB envelope scale.
public func vgMacroIsCgb(_ macro: VgMacro) -> Bool {
    switch macro {
    case .directSound, .directSoundNoResample, .directSoundAlt, .keysplit, .keysplitAll: false
    case .square1, .square1Alt, .square2, .square2Alt,
         .progWave, .progWaveAlt, .noise, .noiseAlt: true
    }
}

/// Returns the base macro ordinal for an envelope family, or -1 for no envelope.
public func vgAdsrFamily(_ macro: VgMacro) -> Int {
    switch macro {
    case .directSound, .directSoundNoResample, .directSoundAlt: Int(VgMacro.directSound.rawValue)
    case .square1, .square1Alt: Int(VgMacro.square1.rawValue)
    case .square2, .square2Alt: Int(VgMacro.square2.rawValue)
    case .progWave, .progWaveAlt: Int(VgMacro.progWave.rawValue)
    case .noise, .noiseAlt: Int(VgMacro.noise.rawValue)
    case .keysplit, .keysplitAll: -1
    }
}

/// Returns the displayed Golden Sun waveform name.
public func vgSynthWaveformName(_ waveform: Int) -> String {
    switch waveform {
    case 0: "Pulse"
    case 1: "Sawtooth"
    default: "Triangle"
    }
}

/// Returns the canonical symbol, before any collision suffix is applied.
public func vgSynthSymbolName(_ desc: VgSynthDesc) -> String {
    switch desc.waveform {
    case 0:
        return String(format: "DirectSoundSynth_GoldenSun_%02X%02X%02X%02X",
                      UInt8(truncatingIfNeeded: desc.baseDuty),
                      UInt8(truncatingIfNeeded: desc.dutyStep),
                      UInt8(truncatingIfNeeded: desc.modDepth),
                      UInt8(truncatingIfNeeded: desc.phase))
    case 1: return "DirectSoundSynth_GoldenSun_Saw"
    default: return "DirectSoundSynth_GoldenSun_Triangle"
    }
}

/// Picks the symbol's typical envelope, then its family's, then an audible fallback.
public func vgDefaultAdsr(_ defaults: VgAdsrDefaults, _ macro: VgMacro, _ symbol: String) -> VgAdsr {
    if !symbol.isEmpty, let match = defaults.bySymbol[symbol] { return match }
    if let match = defaults.byFamily[vgAdsrFamily(macro)] { return match }
    return vgMacroIsCgb(macro)
        ? VgAdsr(attack: 0, decay: 0, sustain: 15, release: 3)
        : VgAdsr(attack: 255, decay: 0, sustain: 255, release: 165)
}

/// Returns true when scalar ToneData updates cannot reproduce the edit.
public func vgVoiceStructuralChange(_ before: VgVoice, _ after: VgVoice) -> Bool {
    before.macro != after.macro || before.symbol != after.symbol ||
        before.keysplitTable != after.keysplitTable
}
